static void drain_bus(zst_bus_t* bus, zst_element_t* coord,
                      int* tx_f, int* rx_f, int* err) {
    zst_event_t* ev = NULL;
    while (zst_bus_pop(bus, &ev, 0) == ZST_OK && ev) {
        switch (ev->type) {
        case ZST_EVENT_ERROR:
            fprintf(stderr, "  [BUS ERR] from %s: %s (code=%d)\n",
                    ev->src && ev->src->ops ? ev->src->ops->name : "?",
                    ev->as.error.message, ev->as.error.result);
            if (err) (*err)++;
            break;
        case ZST_EVENT_WARNING:
            fprintf(stderr, "  [BUS WARN] %s\n", ev->as.error.message);
            break;
        case ZST_EVENT_DANTE_FLOW_CREATED:
            if (ev->as.dante_flow.flow.direction == ZST_DANTE_FLOW_TX) {
                if (coord && zst_dante_video_coordinator_apply_flow(
                        coord, &ev->as.dante_flow.flow) == ZST_OK) {
                    printf("  [BUS] TX video flow idx=%u ch=%u port=%u\n",
                           ev->as.dante_flow.flow.flow_index,
                           ev->as.dante_flow.flow.channel_index,
                           ev->as.dante_flow.flow.port);
                    /* Track this flow for RTP stats */
                    if (g_rtp_tx_count < MAX_RTP_TX_TRACK) {
                        rtp_tx_track_t* t = &g_rtp_tx_track[g_rtp_tx_count++];
                        t->flow_index    = ev->as.dante_flow.flow.flow_index;
                        t->channel_index = ev->as.dante_flow.flow.channel_index;
                        t->port          = ev->as.dante_flow.flow.port;
                        strncpy(t->receiver_address,
                                ev->as.dante_flow.flow.receiver_address ? ev->as.dante_flow.flow.receiver_address : "?",
                                sizeof(t->receiver_address) - 1);
                        t->reported      = 0;
                        t->last_packets  = 0;
                        t->last_errors   = 0;
                    }
                    if (tx_f) (*tx_f)++;
                }
            } else if (ev->as.dante_flow.flow.direction == ZST_DANTE_FLOW_RX) {
                if (coord && zst_dante_video_coordinator_apply_flow(
                        coord, &ev->as.dante_flow.flow) == ZST_OK) {
                    printf("  [BUS] RX video flow idx=%u ch=%u port=%u\n",
                           ev->as.dante_flow.flow.flow_index,
                           ev->as.dante_flow.flow.channel_index,
                           ev->as.dante_flow.flow.port);
                    /* Track this flow for RTP receive stats */
                    if (g_rtp_rx_count < MAX_RTP_RX_TRACK) {
                        rtp_rx_track_t* t = &g_rtp_rx_track[g_rtp_rx_count++];
                        t->flow_index    = ev->as.dante_flow.flow.flow_index;
                        t->channel_index = ev->as.dante_flow.flow.channel_index;
                        t->port          = ev->as.dante_flow.flow.port;
                        strncpy(t->receiver_address,
                                ev->as.dante_flow.flow.receiver_address ? ev->as.dante_flow.flow.receiver_address : "?",
                                sizeof(t->receiver_address) - 1);
                        strncpy(t->transmitter_address,
                                ev->as.dante_flow.flow.transmitter_address ? ev->as.dante_flow.flow.transmitter_address : "?",
                                sizeof(t->transmitter_address) - 1);
                        t->reported      = 0;
                        t->last_packets  = 0;
                        t->last_rejected = 0;
                    }
                    if (rx_f) (*rx_f)++;
                }
            }
            break;
        case ZST_EVENT_DANTE_FLOW_DELETED:
            if (coord)
                (void)zst_dante_video_coordinator_remove_flow(
                    coord, &ev->as.dante_flow.flow);
            break;
        default: break;
        }
        zst_event_destroy(ev);
    }
}

static void inspect_dep(const char* name) {
    char path[512]; struct stat st;
    snprintf(path, sizeof(path), "/dev/shm/%s", name);
    printf("[SHM] %s: ", path);
    if (stat(path, &st) != 0) { fprintf(stderr, "MISSING\n"); return; }
    int fd = open(path, O_RDONLY);
    if (fd < 0) { fprintf(stderr, "open fail\n"); return; }
    void* m = mmap(NULL, st.st_size, PROT_READ, MAP_SHARED, fd, 0);
    close(fd);
    if (m == MAP_FAILED) { fprintf(stderr, "mmap fail\n"); return; }
    dep_diag_header_t* h = m;
    printf("magic=0x%08X %s rate=%u period=%u pc=%llu serial=%u\n",
           h->magic, h->magic == DEP_HEADER_MAGIC ? "OK" : "BAD",
           h->sample_rate, h->samples_per_period,
           (unsigned long long)h->period_count, h->reset_serial);
    munmap(m, st.st_size);
}

/* ══════════════════════════════════════════════════════════════════════════ */
/*  Sine wave verification                                                  */
/*  Matches audiotestsrc's fast_sine_from_phase() with volume=0.8           */
/* ══════════════════════════════════════════════════════════════════════════ */

static void sine_verify_init(sine_verify_state_t* sv, uint32_t sample_rate,
                             double frequency, double volume) {
    memset(sv, 0, sizeof(*sv));
    sv->frequency  = frequency;
    sv->volume     = volume;
    sv->sample_rate = sample_rate;
    sv->phase      = 0.0;
    sv->tolerance  = 0.02;  /* 2% of full-scale S32 ≈ ±419430 LSB */
}

static double sine_verify_next_expected(sine_verify_state_t* sv) {
    /* Reproduce audiotestsrc's fast_sine_from_phase() */
    const double pi = 3.14159265358979323846;
    const double two_pi = 6.28318530717958647692;
    double x = sv->phase * two_pi;
    if (x > pi) x -= two_pi;

    const double b = 4.0 / pi;
    const double c = -4.0 / (pi * pi);
    const double p = 0.225;

    double y = b * x + c * x * (x < 0.0 ? -x : x);
    y = p * (y * (y < 0.0 ? -y : y) - y) + y;

    /* Advance phase */
    double step = (double)sv->sample_rate > 0
                ? sv->frequency / (double)sv->sample_rate : 0.0;
    sv->phase += step;
    while (sv->phase >= 1.0) sv->phase -= 1.0;
    while (sv->phase < 0.0) sv->phase += 1.0;

    /* Apply volume and clamp */
    y *= sv->volume;
    if (y > 1.0) y = 1.0;
    if (y < -1.0) y = -1.0;
    return y;
}

static void sine_verify_process_buffer(sine_verify_state_t* sv,
                                       const int32_t* samples,
                                       uint32_t nb_samples) {
    for (uint32_t i = 0; i < nb_samples; i++) {
        double expected = sine_verify_next_expected(sv);
        /* S32LE: 1.0 → INT32_MAX, -1.0 → INT32_MIN */
        double expected_s32 = expected * 2147483647.0;
        double actual_s32   = (double)samples[i];
        double err = actual_s32 - expected_s32;
        double abs_err = err < 0.0 ? -err : err;

        sv->total_samples++;
        double tol_s32 = sv->tolerance * 2147483647.0;
        if (abs_err <= tol_s32) {
            sv->matched_samples++;
        } else {
            sv->mismatched_samples++;
            if (abs_err > sv->max_error_value) {
                sv->max_error_value = abs_err;
                sv->max_error_sample = sv->total_samples;
            }
        }
    }
}

static void sine_verify_reset(sine_verify_state_t* sv) {
    uint64_t total   = sv->total_samples;
    uint64_t matched = sv->matched_samples;
    uint64_t mism    = sv->mismatched_samples;
    sv->total_samples     = 0;
    sv->matched_samples   = 0;
    sv->mismatched_samples = 0;
    sv->max_error_value   = 0.0;
    sv->max_error_sample  = 0;
    /* Print summary before reset */
    printf("    verify: total=%llu matched=%llu mismatch=%llu (%.2f%%)\n",
           (unsigned long long)total, (unsigned long long)matched,
           (unsigned long long)mism,
           total > 0 ? (double)matched * 100.0 / (double)total : 0.0);
}

/* ══════════════════════════════════════════════════════════════════════════ */
/*  Custom RX verify sink — replaces fake_sink for RX mode                  */
/* ══════════════════════════════════════════════════════════════════════════ */

typedef struct {
    sine_verify_state_t verify;
    uint64_t total_buffers;
    uint64_t total_samples;
    uint64_t channel0_samples;
    uint64_t nonzero_samples;
    uint64_t positive_crossings;
    uint64_t peak_abs;
    long double sum_sq;
    int signal_started;
    int32_t last_channel0;
    int have_last_channel0;
    char wav_path[256];
    FILE* wav_fp;
    uint32_t wav_bytes;
} rx_verify_sink_t;

static zst_result_t rx_verify_open(zst_element_t* el) {
    rx_verify_sink_t* s = el->priv;
    s->total_buffers = 0;
    s->total_samples = 0;
    s->channel0_samples = 0;
    s->nonzero_samples = 0;
    s->positive_crossings = 0;
    s->peak_abs = 0;
    s->sum_sq = 0.0;
    s->signal_started = 0;
    s->last_channel0 = 0;
    s->have_last_channel0 = 0;
    sine_verify_init(&s->verify, 48000, 440.0, 0.8);

    if (s->wav_path[0] != '\0') {
        s->wav_fp = fopen(s->wav_path, "wb");
        if (s->wav_fp) {
            uint8_t hdr[44] = {0};
            memcpy(hdr, "RIFF", 4);
            memcpy(hdr + 8, "WAVE", 4);
            memcpy(hdr + 12, "fmt ", 4);
            uint32_t fmt_len = 16;
            uint16_t fmt_tag = 1; /* PCM */
            uint16_t channels = 2;
            uint32_t rate = 48000;
            uint16_t bits = 16;
            uint32_t byte_rate = rate * channels * (bits / 8);
            uint16_t block_align = channels * (bits / 8);
            memcpy(hdr + 16, &fmt_len, 4);
            memcpy(hdr + 20, &fmt_tag, 2);
            memcpy(hdr + 22, &channels, 2);
            memcpy(hdr + 24, &rate, 4);
            memcpy(hdr + 28, &byte_rate, 4);
            memcpy(hdr + 32, &block_align, 2);
            memcpy(hdr + 34, &bits, 2);
            memcpy(hdr + 36, "data", 4);
            fwrite(hdr, 1, 44, s->wav_fp);
            s->wav_bytes = 0;
            printf("  [WAV] Recording RX audio to %s (48kHz, 16-bit stereo PCM)\n", s->wav_path);
        } else {
            fprintf(stderr, "  [WARN] Failed to open WAV recording file: %s (errno=%d: %s)\n",
                    s->wav_path, errno, strerror(errno));
        }
    }
    return ZST_OK;
}

static zst_result_t rx_verify_process(zst_element_t* el,
                                      zst_buffer_t* in,
                                      zst_buffer_t** out) {
    if (!el) return ZST_ERROR;
    rx_verify_sink_t* s = el->priv;
    (void)out;
    if (!in) return ZST_ERROR;

    /* Verify audio data integrity.  Exact sample matching is kept for same-process
     * tests; signal metrics below validate real cross-device runs where the RX
     * starts at an arbitrary sine phase. */
    if (in->memory.data && in->memory.size > 0) {
        const int32_t* samples = (const int32_t*)in->memory.data;
        uint32_t nb_samples = (uint32_t)(in->memory.size / sizeof(int32_t));
        uint32_t channels = 2;
        const zst_audio_frame_t* af = in->payload;
        if (af && af->channels > 0) channels = af->channels;
        sine_verify_process_buffer(&s->verify, samples, nb_samples);
        s->total_samples += nb_samples;

        if (s->wav_fp) {
            for (uint32_t i = 0; i < nb_samples; i++) {
                int16_t s16 = (int16_t)(samples[i] >> 16);
                fwrite(&s16, sizeof(int16_t), 1, s->wav_fp);
            }
            s->wav_bytes += nb_samples * sizeof(int16_t);
        }
        for (uint32_t i = 0; i < nb_samples; i += channels) {
            int32_t sample = samples[i];
            int64_t value = sample;
            uint64_t abs_value = (uint64_t)(value < 0 ? -value : value);
            if (!s->signal_started) {
                if (abs_value < 21474836ULL) continue; /* ignore startup silence (<1% FS) */
                s->signal_started = 1;
                s->last_channel0 = sample;
                s->have_last_channel0 = 1;
            }
            if (sample != 0) s->nonzero_samples++;
            if (abs_value > s->peak_abs) s->peak_abs = abs_value;
            s->sum_sq += (long double)value * (long double)value;
            if (s->have_last_channel0 && s->last_channel0 <= 0 && sample > 0)
                s->positive_crossings++;
            s->last_channel0 = sample;
            s->have_last_channel0 = 1;
            s->channel0_samples++;
        }
    }
    s->total_buffers++;
    return ZST_OK;
}

static zst_result_t rx_verify_get_property(zst_element_t* el,
                                           const char* name,
                                           char* value_out,
                                           size_t max_len) {
    rx_verify_sink_t* s = el->priv;
    if (strcmp(name, "total-buffers") == 0) {
        snprintf(value_out, max_len, "%llu",
                 (unsigned long long)s->total_buffers);
        return ZST_OK;
    } else if (strcmp(name, "total-samples") == 0) {
        snprintf(value_out, max_len, "%llu",
                 (unsigned long long)s->total_samples);
        return ZST_OK;
    } else if (strcmp(name, "matched-samples") == 0) {
        snprintf(value_out, max_len, "%llu",
                 (unsigned long long)s->verify.matched_samples);
        return ZST_OK;
    } else if (strcmp(name, "mismatched-samples") == 0) {
        snprintf(value_out, max_len, "%llu",
                 (unsigned long long)s->verify.mismatched_samples);
        return ZST_OK;
    } else if (strcmp(name, "max-error") == 0) {
        snprintf(value_out, max_len, "%.1f (at sample %llu)",
                 s->verify.max_error_value,
                 (unsigned long long)s->verify.max_error_sample);
        return ZST_OK;
    } else if (strcmp(name, "integrity-pct") == 0) {
        double pct = s->verify.total_samples > 0
            ? (double)s->verify.matched_samples * 100.0 /
              (double)s->verify.total_samples
            : 0.0;
        snprintf(value_out, max_len, "%.4f%%", pct);
        return ZST_OK;
    } else if (strcmp(name, "signal-rms-pct") == 0) {
        double rms = s->channel0_samples > 0
            ? sqrt((double)(s->sum_sq / (long double)s->channel0_samples)) : 0.0;
        snprintf(value_out, max_len, "%.2f%%", rms * 100.0 / 2147483647.0);
        return ZST_OK;
    } else if (strcmp(name, "signal-peak-pct") == 0) {
        snprintf(value_out, max_len, "%.2f%%",
                 (double)s->peak_abs * 100.0 / 2147483647.0);
        return ZST_OK;
    } else if (strcmp(name, "signal-frequency-hz") == 0) {
        double seconds = s->channel0_samples > 0
            ? (double)s->channel0_samples / 48000.0 : 0.0;
        double hz = seconds > 0.0 ? (double)s->positive_crossings / seconds : 0.0;
        snprintf(value_out, max_len, "%.2f", hz);
        return ZST_OK;
    } else if (strcmp(name, "signal-ok") == 0) {
        double seconds = s->channel0_samples > 0
            ? (double)s->channel0_samples / 48000.0 : 0.0;
        double hz = seconds > 0.0 ? (double)s->positive_crossings / seconds : 0.0;
        double peak_pct = (double)s->peak_abs * 100.0 / 2147483647.0;
        int ok = s->channel0_samples >= 4800 && s->nonzero_samples > 0 &&
                 peak_pct >= 50.0 && peak_pct <= 95.0 && hz >= 420.0 && hz <= 460.0;
        snprintf(value_out, max_len, "%s", ok ? "true" : "false");
        return ZST_OK;
    }
    return ZST_ERROR;
}

static zst_result_t rx_verify_sink_push(zst_pad_t* pad, zst_buffer_t* buf) {
    zst_buffer_t* out = NULL;
    return rx_verify_process(pad ? pad->parent : NULL, buf, &out);
}

static zst_result_t rx_verify_close(zst_element_t* el) {
    rx_verify_sink_t* s = el->priv;
    if (s && s->wav_fp) {
        uint32_t riff_size = 36 + s->wav_bytes;
        uint32_t data_size = s->wav_bytes;
        fseek(s->wav_fp, 4, SEEK_SET);
        fwrite(&riff_size, 4, 1, s->wav_fp);
        fseek(s->wav_fp, 40, SEEK_SET);
        fwrite(&data_size, 4, 1, s->wav_fp);
        fclose(s->wav_fp);
        s->wav_fp = NULL;
        printf("  [WAV] Finished recording: %u bytes (%.2f s) written to %s\n",
               s->wav_bytes, (double)s->wav_bytes / (48000.0 * 2.0 * 2.0), s->wav_path);
    }
    return ZST_OK;
}


/* ── Sine wave verification state ──────────────────────────────────────── */
typedef struct {
    /* TX parameters (must match audiotestsrc defaults in test) */
    double frequency;    /* Hz */
    double volume;       /* 0.0 – 1.0 */
    uint32_t sample_rate;

    /* Running phase accumulator */
    double phase;

    /* Statistics */
    uint64_t total_samples;
    uint64_t matched_samples;   /* within tolerance */
    uint64_t mismatched_samples;
    uint64_t max_error_sample;  /* sample index of worst mismatch */
    double   max_error_value;   /* worst absolute error */

    /* Tolerance: allowed deviation as fraction of full-scale S32 */
    double tolerance;
} sine_verify_state_t;


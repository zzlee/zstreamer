/*============================================================================
    test_dante_av_txrx_integrity.c — Dante A/V TX+RX audio integrity test

    Verifies that audio data received via DEP shared memory matches the
    known sine wave pattern generated by audiotestsrc on the TX side.

    TX side (same machine or --tx):
      audiotestsrc (440Hz sine, 48kHz, S32LE, vol=0.8)
        -> audioresampler -> dantedepaudiosink (DEP shm)

    RX side (--rx):
      dantedepaudiosrc -> audioresampler -> verify sink
        (compares each sample against expected sine wave)

    Usage:
      TX: ./test_dante_av_txrx_integrity --tx [--log file] [dvr_path] [dep_name]
      RX: ./test_dante_av_txrx_integrity --rx [--log file] [dvr_path] [dep_name]
      Both: ./test_dante_av_txrx_integrity [--log file] [dvr_path] [dep_name]
      Default = both TX and RX in same process.

    Log:
      Auto-generates: dante_av_{tx|rx|txrx}_YYYYMMDD_HHMMSS.log
      Or specify: --log <filename>

    Defaults:
      dvr_path = /var/run/dante/dvr
      dep_name = DanteEP
============================================================================*/
